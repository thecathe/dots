#!/usr/bin/env bash
# Behaviour of niri-dms-outputs against a stand-in niri (checks/niri-dms-outputs-stub.sh)
# and hand-written outputs.kdl files: which outputs it turns off and which it
# leaves alone (nested or commented `off`, already off, not connected, the last
# one on), naming an output by "make model serial", waiting for a slow niri,
# the failures, --dry-run. Run by checks/niri-dms-outputs.nix (niri-dms-outputs
# and jq on PATH); run by hand the same way.
set -u

root=$(mktemp -d)
trap 'rm -rf "$root"' EXIT
export STUB_DIR=$root/stub NIRI_DMS_OUTPUTS_TRIES=3
kdl_file=$root/outputs.kdl

fails=0
ok() { printf 'ok    %s\n' "$1"; }
bad() {
  printf 'FAIL  %s\n' "$1"
  fails=$((fails + 1))
}
check() { # check NAME CONDITION-COMMAND...
  local name=$1
  shift
  if "$@"; then ok "$name"; else bad "$name"; fi
}

two_on='{
  "DP-1": {"make": "PNP(AOC)", "model": "24G4", "serial": "12VR1HA009770", "logical": {"x": 1080}},
  "HDMI-A-1": {"make": "Dell Inc.", "model": "DELL P2419H", "serial": "2KGB1Y2", "logical": {"x": 0}}
}'
hdmi_off='{
  "DP-1": {"make": "PNP(AOC)", "model": "24G4", "serial": "12VR1HA009770", "logical": {"x": 1080}},
  "HDMI-A-1": {"make": "Dell Inc.", "model": "DELL P2419H", "serial": "2KGB1Y2", "logical": null}
}'

# What DMS wrote for the "1 Screen" profile on 2026-11-25, and what it writes for "2 Screens".
one_screen='// Auto-generated by DMS - do not edit manually

output "HDMI-A-1" {
    off
    mode "1920x1080@60.000"
    scale 1
    transform "90"
    position x=0 y=0
}

output "DP-1" {
    mode "1920x1080@180.003"
    scale 1
    position x=1080 y=0
    variable-refresh-rate on-demand=true
}
'
two_screens='// Auto-generated by DMS - do not edit manually

output "HDMI-A-1" {
    mode "1920x1080@60.000"
    scale 1
    transform "90"
    position x=0 y=0
}

output "DP-1" {
    mode "1920x1080@180.003"
    scale 1
    position x=1080 y=0
    variable-refresh-rate on-demand=true
}
'

# fresh_stub OUTPUTS-JSON: an empty stub directory serving that niri state.
fresh_stub() {
  rm -rf "$STUB_DIR"
  mkdir -p "$STUB_DIR"
  printf '%s' "$1" >"$STUB_DIR/outputs.json"
}
# run_on KDL-TEXT OUTPUTS-JSON [ARGS...]: a fresh stub, the outputs.kdl, one run.
# Leaves $status, $out (everything it printed) and $offs (the outputs it turned
# off, comma-separated) behind.
run_on() {
  local kdl=$1 json=$2
  shift 2
  fresh_stub "$json"
  printf '%s' "$kdl" >"$kdl_file"
  run_script "$@"
}
run() { run_on "$1" "$two_on"; }
run_script() { # the script on the outputs.kdl as it now stands
  out=$(niri-dms-outputs "$@" "$kdl_file" 2>&1)
  status=$?
  offs=$(paste -sd, "$STUB_DIR/off.log" 2>/dev/null || true)
}
offs_are() { [ "$offs" = "$1" ]; }
status_is() { [ "$status" = "$1" ]; }
said() { grep -qF -- "$1" <<<"$out"; }
silent() { [ -z "$out" ]; }

# --- the real thing
run "$one_screen"
check "1 Screen: HDMI-A-1 is turned off, and only it" offs_are "HDMI-A-1"
check "1 Screen: exit status 0" status_is 0

# --- nothing to do
run "$two_screens"
check "2 Screens: nothing is turned off" offs_are ""
check "2 Screens: exit status 0" status_is 0
check "2 Screens: silent" silent

rm -f "$kdl_file"
fresh_stub "$two_on"
run_script
check "no outputs.kdl: nothing is turned off" offs_are ""
check "no outputs.kdl: exit status 0" status_is 0
check "no outputs.kdl: silent" silent

# --- which `off` counts
run 'output "DP-1" {
    mode "1920x1080@60.000"
}
output "HDMI-A-1" {
    off
}
'
check "off in the second block" offs_are "HDMI-A-1"

run 'output "HDMI-A-1" {
    layout {
        hot-corners {
            off
        }
    }
    mode "1920x1080@60.000"
}
'
check "an off nested in the block does not count" offs_are ""

run 'output "HDMI-A-1" {
    // off
    mode "1920x1080@60.000"
}
'
check "an off in a comment does not count" offs_are ""

run 'output "HDMI-A-1" {
    off // DMS: profile 1 Screen
}
'
check "an off with a trailing comment counts" offs_are "HDMI-A-1"

run 'off
output "HDMI-A-1" {
    mode "1920x1080@60.000"
}
'
check "an off outside any output block does not count" offs_are ""

run 'output "Dell Inc. DELL P2419H 2KGB1Y2" {
    off
}
'
check "an output named by make, model and serial" offs_are "HDMI-A-1"

# --- what it leaves alone
run_on "$one_screen" "$hdmi_off"
check "already off: not turned off again" offs_are ""
check "already off: says so" said "HDMI-A-1 is already off"
check "already off: exit status 0" status_is 0

run 'output "DP-3" {
    off
}
'
check "not connected: left alone" offs_are ""
check "not connected: says so" said "DP-3 is not connected"
check "not connected: exit status 0" status_is 0

run 'output "DP-1" {
    off
}
output "HDMI-A-1" {
    off
}
'
check "both marked off: only one is turned off" offs_are "DP-1"
check "both marked off: the last one on is refused" said "HDMI-A-1 is the only output that is on"
check "both marked off: exit status 0" status_is 0

# --- niri
fresh_stub "$two_on"
printf '%s' "$one_screen" >"$kdl_file"
echo 2 >"$STUB_DIR/answer-after"
run_script
check "a niri that answers on the third try: still turned off" offs_are "HDMI-A-1"
check "a niri that answers on the third try: exit status 0" status_is 0

fresh_stub "$two_on"
echo 3 >"$STUB_DIR/answer-after"
run_script
check "a niri that never answers: nothing is turned off" offs_are ""
check "a niri that never answers: exit status 1" status_is 1
check "a niri that never answers: says so" said "niri did not answer"

fresh_stub "$two_on"
touch "$STUB_DIR/fail-off"
run_script
check "niri refuses the command: exit status 1" status_is 1
check "niri refuses the command: says so" said "could not turn off HDMI-A-1"

# --- options
run_on "$one_screen" "$two_on" --dry-run
check "--dry-run: nothing is turned off" offs_are ""
check "--dry-run: says what it would do" said "would turn off HDMI-A-1"
check "--dry-run: exit status 0" status_is 0

run_on "$one_screen" "$two_on" --nonsense
check "an unknown option: exit status 2" status_is 2
check "an unknown option: nothing is turned off" offs_are ""

if [ "$fails" -ne 0 ]; then
  echo "$fails failed" >&2
  exit 1
fi
